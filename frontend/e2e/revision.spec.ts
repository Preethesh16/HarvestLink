import {test, expect} from '@playwright/test';
import {loginAs} from './auth';
import {resolve} from 'node:path';
const API=process.env.TEST_API_URL||'http://127.0.0.1:8000';
test('Excel preview, dated government prices and buyer-only navigation',async({page})=>{
 await loginAs(page); await page.request.post(API+'/api/reset'); await loginAs(page);
 await page.getByRole('button',{name:'My harvest',exact:true}).click();
 await page.getByRole('button',{name:'Import Excel / CSV',exact:true}).click();
 await page.locator('input[type=file]').setInputFiles(resolve('../demo-data/farmer-harvest.xlsx'));
 await expect(page.locator('.sheet-preview')).toContainText('farmer-harvest.xlsx');
 await expect(page.locator('.sheet-preview')).toContainText('Brinjal');
 await page.getByRole('button',{name:'Validate & import',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await expect(page.getByRole('heading',{name:'Cucumber Local',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Mandi prices',exact:true}).click();
 await expect(page.locator('.government-provenance')).toContainText('2026-10-19');
 await page.getByRole('textbox',{name:'Search government prices'}).fill('Tomato');
 await expect(page.locator('.government-table tbody')).toContainText('17.69');
 await expect(page.locator('.inline-note')).toContainText('Cucumber');
 await loginAs(page,'r1');
 await expect(page.getByRole('button',{name:'My harvest',exact:true})).toHaveCount(0);
 await expect(page.getByRole('button',{name:'What to grow next',exact:true})).toHaveCount(0);
 await expect(page.getByRole('button',{name:'Mandi prices',exact:true})).toHaveCount(0);
 await expect(page.locator('.farm-stat,.hero-stamp')).toHaveCount(0);
 await expect(page.getByRole('button',{name:'Inventory & forecast',exact:true})).toBeVisible();
});
test('Negotiation replay and delivery simulation preserve transaction approval',async({page})=>{
 await loginAs(page); await page.request.post(API+'/api/reset'); await loginAs(page);
 await page.getByRole('button',{name:'Negotiations',exact:true}).click();
 await page.getByRole('button',{name:'Run negotiation',exact:true}).click();
 await expect(page.locator('.offer-card')).toHaveCount(3);
 await expect(page.getByRole('region',{name:'Negotiation replay'})).toBeVisible();
 await page.getByRole('button',{name:'Choose this offer',exact:true}).first().click();
 await loginAs(page,'r1');
 await page.getByRole('button',{name:'Orders',exact:true}).click();
 await expect(page.getByRole('button',{name:'Play delivery simulation',exact:true})).toBeDisabled();
 await page.getByRole('button',{name:'Confirm agreement',exact:true}).click();
 await page.getByRole('button',{name:'Fund simulated payment',exact:true}).click();
 await page.getByRole('button',{name:'Play delivery simulation',exact:true}).click();
 await expect(page.getByRole('progressbar',{name:'Simulated journey progress'})).toHaveAttribute('value','100',{timeout:20000});
 await expect(page.locator('.order .badge').first()).toHaveText('funded');
});
